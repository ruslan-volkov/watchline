#!/usr/bin/env bash
# Point the Expo app at the local Supabase stack.
#
# Expo loads .env.local ahead of .env, so this leaves the cloud-pointing .env
# untouched: delete .env.local to switch back. Both files are gitignored.
#
# Hosts: the iOS simulator shares the host's loopback, so 127.0.0.1 works as is.
# An Android emulator needs 10.0.2.2 and a physical device needs this machine's
# LAN address — pass it as the first argument:
#   ./scripts/use-local-backend.sh 192.168.1.20
set -euo pipefail
cd "$(dirname "$0")/.."

host="${1:-127.0.0.1}"
status=$(supabase status -o env)
api=$(printf '%s\n' "$status" | sed -nE 's/^API_URL="(.*)"$/\1/p')
anon=$(printf '%s\n' "$status" | sed -nE 's/^ANON_KEY="(.*)"$/\1/p')

if [ -z "$api" ] || [ -z "$anon" ]; then
  echo "Could not read API_URL / ANON_KEY from 'supabase status'." >&2
  echo "Is the local stack running? Start it with: supabase start" >&2
  exit 1
fi

api="${api/127.0.0.1/$host}"

cat > .env.local <<EOF
# Generated by scripts/use-local-backend.sh — not committed (gitignored).
# Overrides .env so the app talks to the local stack. Delete to go back to cloud.
# Reload the app (shake → Reload) after changing this file.
EXPO_PUBLIC_SUPABASE_URL=$api
EXPO_PUBLIC_SUPABASE_ANON_KEY=$anon
# Empty on purpose: the app falls back to src/media/mock.ts, so local work needs
# no TMDB token.
EXPO_PUBLIC_TMDB_ACCESS_TOKEN=
EOF

echo "Wrote .env.local -> $api"
